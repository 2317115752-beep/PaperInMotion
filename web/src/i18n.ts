export function translateBackendMessage(value: string, language: Language) {
  if (language === 'zh') {
    for (const [pattern, translated] of chineseBackendMessages) {
      const match = value.match(pattern);
      if (match) return translated.replace(/\$(\d+)/g, (_, index: string) => match[Number(index)] || '');
    }
    return value;
  }
  if (!/[\u3400-\u9fff]/.test(value)) return value;
  for (const [pattern, translated] of englishBackendMessages) {
    const match = value.match(pattern);
    if (match) return translated.replace(/\$(\d+)/g, (_, index: string) => match[Number(index)] || '');
  }
  return undefined;
}
